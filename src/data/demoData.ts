/**
 * Participant-field set for the two management simulations: name (required),
 * role, department and cohort are shown; email, employee-id and the custom
 * field stay hidden. Anonymous participation is off (full name is required).
 */
function managementParticipantFields(): ParticipantField[] {
  const shown = new Set<ParticipantField['type']>(['fullName', 'role', 'department', 'cohort'])
  return participantFieldDefaults.map((field) => ({ ...field, enabled: shown.has(field.type) }))
}

